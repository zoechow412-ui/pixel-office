import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const context={};context.globalThis=context;
vm.runInNewContext(fs.readFileSync("web/layout.js","utf8"),context);
const L=context.POLayout;
const ids=["manager","sales","marketing","video","project-manager","architectural","plumbing","electrical-fire","researcher","documentation","estimating","finance","procurement","developer"];
assert.equal(L.MAX_EMP>=14,true);
const scene=L.scene(null,ids,"default");
assert.equal(scene.build.desks.length,14);
assert.equal(scene.assign.size,14);
const valid=L.check(scene.items,{empCount:14});
assert.equal(valid.ok,true,JSON.stringify(valid.errors));
for(const id of ids)assert.ok(scene.assign.get(id),"Missing desk for "+id);
const byId=Object.fromEntries(scene.items.filter(x=>x.type==="desk").map(x=>[x.emp,x]));
assert.deepEqual([byId.plumbing.tx,byId.plumbing.ty],[13,11]);
assert.equal(byId["project-manager"].tx,byId.electrical-fire.tx);
assert.equal(byId.sales.tx,byId.marketing.tx);
assert.equal(byId.researcher.tx,byId.documentation.tx);
const next=L.scene(null,["manager","developer","sales"],"default");
assert.equal(next.build.desks.length,3,"Other offices remain compact");
console.log("Hang Fai 14-person floor plan and department seating validated.");
