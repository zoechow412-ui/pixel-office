import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
const context={};context.globalThis=context;
vm.runInNewContext(fs.readFileSync("web/layout.js","utf8"),context);
const L=context.POLayout;
const ids=["manager","sales","marketing","video","project-manager","architectural","plumbing","electrical-fire","researcher","documentation","estimating","finance","procurement","developer"];
assert.equal(L.MAX_EMP>=14,true);
const scene=L.scene(null,ids,"default");
assert.equal(scene.build.desks.length,14);
assert.equal(scene.assign.size,14);
const valid=L.check(scene.items,{empCount:14});
assert.equal(valid.ok,true,JSON.stringify(valid.errors));
for(const id of ids)assert.ok(scene.assign.get(id),"Missing desk for "+id);
const byId=Object.fromEntries(scene.items.filter(x=>x.type==="desk").map(x=>[x.emp,x]));
assert.deepEqual([byId.plumbing.tx,byId.plumbing.ty],[16,4]);
assert.deepEqual([byId.manager.tx,byId.manager.ty],[1,3]);
assert.deepEqual([byId.sales.tx,byId.sales.ty],[4,3]);
assert.deepEqual([byId.marketing.tx,byId.marketing.ty],[1,6]);
assert.deepEqual([byId.video.tx,byId.video.ty],[4,6]);
assert.equal(byId["project-manager"].ty,byId["electrical-fire"].ty);
assert.deepEqual([byId.researcher.tx,byId.researcher.ty],[25,11]);
assert.deepEqual([byId.finance.tx,byId.finance.ty],[28,14]);
assert.deepEqual([byId.procurement.tx,byId.procurement.ty],[1,11]);
assert.deepEqual([byId.developer.tx,byId.developer.ty],[4,11]);
const inRoom=(seat,room)=>seat.tx>=room.x0&&seat.tx<=room.x1&&seat.ty>=room.y0&&seat.ty<=room.y1;
const wingByKey=Object.fromEntries(L.ROOMS.map(r=>[r.key,r]));
for(const id of ["manager","sales","marketing","video"])assert.ok(inRoom(byId[id],wingByKey.kitchen),id+" must sit in executive room");
for(const id of ["project-manager","architectural","plumbing","electrical-fire"])assert.ok(inRoom(byId[id],wingByKey.office),id+" must sit in engineering room");
for(const id of ["researcher","documentation","estimating","finance"])assert.ok(inRoom(byId[id],wingByKey.archive),id+" must sit in compliance room");
for(const id of ["developer","procurement"])assert.ok(inRoom(byId[id],wingByKey.lounge),id+" must sit in IT / purchasing room");
assert.equal(L.HQ_WINGS.length,4,"Four real department rooms, not drawn stripes");
assert.equal(scene.items.filter(it=>it.type==="counter").length,0,"The executive room must be cleared for desks");
const next=L.scene(null,["manager","developer","sales"],"default");
assert.equal(next.build.desks.length,3,"Other offices remain compact");
console.log("Hang Fai 14-person floor plan and department seating validated.");
